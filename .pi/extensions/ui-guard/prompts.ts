/**
 * 共享提示词约束。
 *
 * 两个目的：
 *   1. 把「只准改视觉层」写进模型的任务约束，与守卫的硬拦截形成双保险
 *   2. 避免产出「AI 感」界面——目标是还原参考图的设计意图，不是堆现代感元素
 */

export const UI_RULES = `
硬性约束（违反即视为任务失败）：
1. 只允许改视觉层：模板/JSX、DOM 结构、class 名、样式文件、纯展示型子组件。
2. 严禁改动：API 请求与响应处理、数据获取与提交、状态语义、hooks/composables 行为、
   effect 依赖、事件处理函数的实现、状态管理逻辑、路由、登录鉴权、权限、业务计算。
3. 事件绑定的目标必须保持不变。@click="handleSubmit" 不能变成别的函数，
   onClick={handleSubmit} 同理。只能改视觉反馈，不能改调用对象。
4. 不要新增或删除 import，除非该 import 纯粹用于样式或纯展示组件。
5. 沿用项目现有的样式技术栈。项目用 SCSS 就写 SCSS，用 CSS Modules 就写 CSS Modules，
   用 Vue scoped CSS 就写 scoped CSS。禁止顺手迁移到 Tailwind 或任何其他方案。
6. 不要产出「AI 感」界面：不要堆渐变、毛玻璃、过度圆角、过度阴影、装饰性图标、
   大范围 transition-all，也不要添加参考图里不存在的 UI 元素。
7. 判断依据集中在：布局、间距、比例、排版、字号层级、色彩、圆角、阴影、内容密度、响应式行为。
`.trim();

export const CAPTURE_DONE = "CAPTURE_DONE";

/**
 * 委托模型自己截图。
 *
 * `npx playwright screenshot <url>` 只能加载 URL，无法点击。
 * 实际项目里目标界面常常藏在 modal / 页签 / 登录后，甚至需要数据才能渲染——
 * 例如 Tauri 单页应用只有 / 一个路由，目标在侧栏点开的弹窗里。
 * 这种情况下固定 URL 截图拿到的永远是首页，视觉比对完全无意义。
 * 模型手里有 playwright 浏览器工具，能导航、点击、注入演示数据，比插件直接截可靠。
 */
export function buildCapturePrompt(
	url: string,
	outPath: string,
	steps: string,
	verified = true,
): string {
	return [
		"现在请把你刚改完的界面截图下来，用于与参考图做视觉比对。",
		"",
		`1. 用浏览器工具打开 ${url}`,
		...(verified
			? []
			: [
					"   ⚠️ 这个地址**未能证实属于本项目**（端口能连上但页面标题对不上或取不到）。",
					"   截图前先确认页面确实是本仓库的应用：不是的话，请找出本项目真实的 dev server 地址",
					"   （看 package.json / vite 配置 / docker-compose），仍找不到就回复 CAPTURE_FAILED。",
					"   截错项目的图会让整轮视觉比对得出完全错误的结论。",
				]),
		...(steps && steps !== "无" ? [`2. 按以下路径导航到目标界面：${steps}`] : []),
		"3. 如果界面因为没数据而是空的，可以在浏览器里临时注入演示数据，",
		"   但**不得把演示数据写进源码**，也不得修改任何业务文件。",
		`4. 截图保存到：${outPath}`,
		"   先把视口设成 1440x900 左右；目标区域若超出一屏，用整页截图，",
		"   否则用视口截图即可。必须能完整看到目标区域，不要只截一小块。",
		"5. 自己中途查看效果的截图请存到 .ai/screenshots/scratch/ 下，",
		`   \`${outPath}\` 只放这一轮的最终结果，否则人工验收时分不清哪张是哪轮的。`,
		"6. 临时文件不用你清理，扩展会自动处理。",
		"",
		`截图保存完成后，只回复一行：${CAPTURE_DONE}`,
		"如果实在无法截图（没有浏览器工具、页面打不开等），说明原因并回复：CAPTURE_FAILED",
	].join("\n");
}

/** 自动闭环中追加的说明，避免模型停下来问用户 */
